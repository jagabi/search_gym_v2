"""Effective policy metadata shared by CLI, saved configuration and runtime traces."""


def raw_policy(config, method):
    if method != "jevtree" or config.jev_strategy != "raw":
        return None
    progressive = config.jev_traversal == "progressive"
    return {
        "decision_provider": config.decision_provider,
        "decision_model": "pplx-decider-v1.2" if config.decision_provider == 'pplx' else config.jev_model,
        "decision_limits": {"requests_per_second": 6, "reserved_tokens_per_minute": 12000000}
                           if config.decision_provider == 'pplx' else None,
        "traversal": config.jev_traversal,
        "expected_traversal": config.jev_expected_traversal or None,
        "tools": ["web_search", "read_source", "continue_search"] if progressive else ["web_search"],
        "research_state": progressive,
        "final_evidence_review": progressive or config.finalize_answer,
        "http_wave": {"requests": config.jev_concurrency, "questions_per_request": config.jev_packet_questions,
                      "question_budget": config.jev_inflight_questions,
                      "wait_for_all": config.decision_provider != 'pplx'},
        "decision_batching": {"scope": "same_search_phase_identical_state",
                              "source_token_budget": config.jev_bundle_tokens,
                              "source_binding": "one_unchanged_state_multiple_keys",
                              "partial_results": "preserve_valid_keys"},
        "max_searches": config.max_searches,
        "initial_pages": config.jev_entries,
        "entry_candidates": config.jev_entry_candidates if config.jev_rank_entries or config.jev_traversal == 'beam' else None,
        "entry_selection": "fetch_all_then_source_prefix" if config.jev_traversal == 'beam' else
                           "d3" if config.jev_rank_entries else "search_order",
        "entry_complement_slots": 0,
        "visits_per_search_limit": config.jev_fetch_budget,
        "visits_per_continue": config.jev_expand_batch if progressive else None,
        "parents_per_action_limit": config.jev_parent_limit if progressive else None,
        "read_quotas": None if config.jev_traversal == "beam" else [config.jev_direct_reads, config.jev_query_reads],
        "complementary_reads": config.jev_diverse_reads and config.jev_traversal != "beam",
        "complementary_read_context": "selected_evidence_chunks" if config.jev_traversal == "best_first" and config.jev_diverse_reads else None,
        "link_parent_beam": config.jev_frontier_width if not progressive and config.jev_traversal == 'beam' else None,
        "link_expansion": ("inspection_then_joint_bundle_evidence_and_links" if config.jev_traversal == 'beam' else
                           "progressive" if progressive else "missing_relation_then_links"),
        "branch_control": {"actions": ["inspect", "skip"],
                           "selection": "single_inspect_value", "depth_barrier": True,
                           "inspect_floor": config.jev_floor,
                           "inspections_per_depth": config.jev_frontier_width,
                           "near_tie": {"margin": config.jev_tie_margin,
                                        "max_width": max(config.jev_tie_width, config.jev_frontier_width),
                                        "applies_to": ["inspection", "parent_links", "child_frontier"]}
                                       if config.jev_tie_margin > 0 else None,
                           "final_source_quotas": None,
                           "return_selection": "all_inspected_bundles_by_evidence_value",
                           "evidence_key": "evidence_value",
                           "last_read": "does_not_end_traversal",
                           "early_return": False,
                           "preview_state": ["page_title", "page_text"],
                           "entry_preview_state": ["page_title", "search_snippet", "page_text"],
                           "entry_title_snippet": "complete_search_metadata_within_total_state_budget",
                           "preview_state_tokens": config.jev_page_tokens,
                           "bundle_state_tokens": config.jev_bundle_tokens,
                           "title": "search_title_at_depth1_reader_title_at_deeper_depths",
                           "links": "joint_with_evidence_keys_on_observed_bundle",
                           "link_question": "compact_record_route_with_destination_url",
                           "visited_links": "filtered_before_questions"} if config.jev_traversal == 'beam' else None,
        "evidence_first": False,
        "read_dedup": config.jev_read_dedup,
        "navigation_notice_tokens": config.jev_notice_tokens,
        "navigation_notice_items": "linked_pages_only" if config.jev_search_results else "search_results_and_linked_pages",
        "search_results_block": {"fields": ["rank", "title", "url", "status", "snippet"],
                                 "position": "before_excerpts",
                                 "budget": "outside_output_tokens",
                                 "excluded": "pages_blocked_as_evaluation_material"}
                                if config.jev_search_results else None,
        "output_tokenizer": "main_model",
        "body_output_tokens": config.jev_output_tokens - min(config.jev_notice_tokens, config.jev_output_tokens//3),
        "document_routing": {"selector": "d3", "min_bundles": config.jev_tree_min_bundles,
            "observation": "one_parent_card_multiple_range_keys",
            "state_tokens": config.jev_bundle_tokens,
            "initial_branch": min(32, config.jev_region_branch * config.jev_region_beam),
            "branch": config.jev_region_branch, "beam": config.jev_region_beam,
            "leaf_bundles": config.jev_leaf_bundles} if config.jev_document_tree else None,
        "evidence_unit": {"kind": "whole_bundle", "tokenizer": "d3",
                          "max_tokens": config.jev_bundle_tokens, "atomic_rescoring": False,
                          "neighbor_expansion": False},
        "question_targets_not_limits": {"visits": config.jev_target_visits,
            "reads": config.jev_target_reads, "parent_expansions": config.jev_target_expansions} if progressive else None,
    }
